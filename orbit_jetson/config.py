# Подтверждение: номер добавляется в список только после N циклов детекции (2 = быстрее, 3 = меньше ложных)
ALPR_CONFIRM_CYCLES = 2
# Окно подтверждения, секунды (тот же номер должен появиться снова в течение этого времени)
