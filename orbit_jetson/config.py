"""
Настройки приложения Orbit_Jetson.
API-ключ хранится в api_key.txt (одна строка, без пробелов).
"""
from pathlib import Path

def _load_api_key() -> str:
    path = Path(__file__).parent / "api_key.txt"
    try:
        return path.read_text(encoding="utf-8").strip()
    except FileNotFoundError:
        return ""

API_TOKEN = _load_api_key()

# Адрес сервера Orbit_Backend (без завершающего слэша)
BACKEND_URL = "http://localhost:8000"

# Интервал отправки телеметрии (GPS) на сервер, секунды
TELEMETRY_INTERVAL_SEC = 8

# Номер патрульного автомобиля (обязательное поле для API телеметрии)
PATROL_LICENSE_PLATE = "A000AA00"

# Максимальное количество отображаемых распознанных номеров в UI
MAX_DISPLAYED_PLATES = 10

# Не отправлять на сервер один и тот же номер повторно в течение этого времени (часы)
DETECTION_DEDUP_HOURS = 12

# --- Камера ---
# Источник видео: с телефона (Iriun и т.п.) или вебкамера.
# На ноутбуке: 0 часто встроенная вебка, 1 или 2 — виртуальная камера с телефона (Iriun).
# Укажите 1 (или 2), чтобы брать картинку с телефона, а не с встроенной вебки.
CAMERA_INDEX = 2

# --- ALPR (nomeroff-net) ---
# True = все вычисления на CPU (медленно, но без видеокарты). False = использовать GPU (NVIDIA, нужен PyTorch с CUDA).
# У вас RTX 3050 — оставьте False и установите PyTorch с CUDA: https://pytorch.org (выбрать CUDA 11.8 или 12.x).
ALPR_USE_CPU = False
# Минимальная уверенность (0.0–1.0). Выше = меньше ложных, но можно пропустить размытые номера.
# Если на другом ПК номера не находятся — поставьте 0.70 или 0.75 (камера может давать хуже картинку).
ALPR_CONFIDENCE_MIN = 0.85
# Код страны для подписи над номером (KZ, RU, UA, EU и т.д.)
ALPR_COUNTRY_CODE = "KZ"
# Метка региона для пайплайна nomeroff-net (OCR/классификация). По умолчанию из ALPR_COUNTRY_CODE.
# Варианты: "kz", "ru", "eu_ua_2015", "eu" — см. документацию nomeroff-net. Пустая строка = авто из кода страны.
ALPR_DEFAULT_LABEL = ""
# Включить апскейл зон номеров в пайплайне (может улучшить распознавание при плохом качестве, но медленнее).
ALPR_UPSCALING = False
# Качество JPEG при сохранении кадра для распознавания (1–100). Выше = лучше качество, чуть дольше.
ALPR_JPEG_QUALITY = 95
# Только казахстанские/СНГ форматы (000AAA00, A000AAA). Европейские номера отключены.
ALPR_ALLOW_EU = False
# Обработка не в каждом кадре, а в каждом N-м (1 = каждый кадр, 2 = каждый второй)
ALPR_DETECT_EVERY_N_FRAMES = 2
# Подтверждение: номер добавляется в список только после N циклов детекции (2 = быстрее, 3 = меньше ложных)
ALPR_CONFIRM_CYCLES = 2
# Окно подтверждения, секунды (тот же номер должен появиться снова в течение этого времени)
ALPR_CONFIRM_SECONDS = 2.5
# Минимальный размер рамки детекции (px): отсекает мелкий шум и далёкие объекты
ALPR_MIN_BBOX_WIDTH = 60
ALPR_MIN_BBOX_HEIGHT = 18
ALPR_MIN_BBOX_AREA = 1100
# Рисовать синие боксы детектора (в Nomeroff-Net это те же номера, не отдельно «машины»). False = только зелёные рамки номеров.
DRAW_OBJECT_BOXES = False
# При уверенности выше этой — номер добавляется в список сразу, без ожидания второго кадра (чтобы не терять видимые номера)
ALPR_HIGH_CONF_ADD_AT_ONCE = 0.90

